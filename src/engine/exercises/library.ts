import type { Exercise } from "../types";

/**
 * Seed exercise library.
 *
 * `stress` rates how much each body area is loaded (1 low, 2 moderate, 3 high).
 * The safety rules use it to avoid aggravating reported pain or past injuries.
 * `easier` / `harder` form progression ladders within a movement pattern.
 */

type Def = Omit<Exercise, "where" | "impact" | "complexity" | "tags" | "alternatives" | "safety" | "muscles" | "stress"> &
  Partial<Pick<Exercise, "where" | "impact" | "complexity" | "tags" | "alternatives" | "safety" | "muscles" | "stress">>;

const ANYWHERE: Exercise["where"] = ["home", "gym", "outdoors"];
const INDOOR: Exercise["where"] = ["home", "gym"];
const GYM: Exercise["where"] = ["gym"];
const OUTDOORS: Exercise["where"] = ["outdoors"];

function ex(d: Def): Exercise {
  return {
    where: d.equipment.length === 0 ? ANYWHERE : INDOOR,
    impact: "low",
    complexity: 1,
    tags: [],
    alternatives: [],
    safety: [],
    muscles: [],
    stress: {},
    ...d,
  };
}

